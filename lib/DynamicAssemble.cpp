#pragma once

#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <string>

// Wrapper to the xa command-line compiler in case we need to generate code on
// the fly
namespace DynamicAssemble {
using std::string;
int assemble(string assemblyText, uint8_t *buffer, size_t bufferSize) {
  using std::fread;
  using std::perror;

  // Redirect stderr to stdout to catch all assembly warnings/errors
  string command = "xa /dev/stdin -o - 2>&1 <<< " + string(assemblyText);

  FILE *pipe = popen(command.c_str(), "r");
  if (!pipe)
    return perror("popen failed"), -1;

  size_t bytes_read = fread((char *)buffer, 1, bufferSize, pipe);
  if (bytes_read > bufferSize) {
    return perror("Generated bytes too large. This is meant for one "
                  "instruction at a time"),
           -1;
  }

  pclose(pipe);

  return bytes_read;
}
} // namespace DynamicAssemble

